// MuJoCo: frame.xml is the model (static body, visual profile meshes in group 1, collision
// boxes in group 3, renderable cameras with their resolution and fovy), scene.xml adds a
// floor, lights and a skybox. MuJoCo cameras look down their local -z with +y up.
import { Model } from '../model.ts';
import { f, m3, fl, looks, MEMBER_ROT, memberMid, cameraFrames, safe, lengthsOf, meshName } from './common.ts';

export function mjcf(m: Model, name = 'table_generator'): string {
  const L = looks(m), out: string[] = [];
  const offW = Math.max(1920, ...m.cameras.map(c => c.spec.width)), offH = Math.max(1080, ...m.cameras.map(c => c.spec.height));
  out.push(`<!-- Generated by Table Generator. Origin on the floor under the table centre, z up. -->`,
    `<mujoco model="${name}">`,
    `  <compiler angle="radian" meshdir="meshes" autolimits="true"/>`,
    `  <visual><global offwidth="${offW}" offheight="${offH}"/></visual>`,
    `  <default>`,
    `    <default class="frame_visual"><geom type="mesh" contype="0" conaffinity="0" group="1" density="0"/></default>`,
    `    <default class="frame_collision"><geom group="3" rgba="0.6 0.6 0.6 1" friction="0.8 0.005 0.0001"/></default>`,
    `  </default>`,
    `  <asset>`);
  for (const l of Object.values(L)) out.push(`    <material name="${l.name}" rgba="${fl(l.rgba, 4)}" specular="${f(l.metallic * 0.5, 2)}" shininess="${f(1 - l.roughness, 2)}"/>`);
  for (const { prof, L } of lengthsOf(m)) out.push(`    <mesh name="${meshName(prof, L)}" file="profile_${prof}.stl" scale="1 1 ${f(L / 1000)}"/>`);
  out.push(`  </asset>`, `  <worldbody>`, `    <body name="frame" pos="0 0 0">`,
    `      <inertial pos="${m3(m.com)}" mass="${f(m.mass, 3)}" fullinertia="${fl(m.inertia)}"/>`);
  for (const pt of m.parts) {
    if (pt.kind === 'camera') continue;
    const mat = L[pt.role].name;
    if (pt.member) {
      out.push(`      <geom name="${pt.id}_visual" class="frame_visual" mesh="${meshName(pt.member.prof, Math.round(pt.member.length * 10) / 10)}" pos="${m3(memberMid(pt))}" quat="${fl(MEMBER_ROT[pt.member.axis].quat)}" material="${mat}"/>`);
      pt.boxes.forEach(b => out.push(`      <geom name="${pt.id}" class="frame_collision" type="box" pos="${m3(b.c)}" size="${m3(b.s.map(v => v / 2) as [number, number, number])}" material="${mat}"/>`));
      continue;
    }
    const cls = pt.collide ? '' : ' contype="0" conaffinity="0" group="1"';
    pt.boxes.forEach((b, i) => out.push(`      <geom name="${pt.id}_${i}" type="box" pos="${m3(b.c)}" size="${m3(b.s.map(v => v / 2) as [number, number, number])}" material="${mat}"${cls}/>`));
    pt.cyls.forEach((c, i) => out.push(`      <geom name="${pt.id}_c${i}" type="cylinder" fromto="${m3(c.a)} ${m3(c.b)}" size="${f(c.r / 1000)}" material="${mat}"${cls}/>`));
  }
  out.push(`      <site name="worktop" pos="${m3([0, 0, m.worktopZ])}" size="0.01" rgba="1 0.8 0 1" group="4"/>`);
  for (const c of m.cameras) {
    const n = safe(c.spec.name), gl = cameraFrames(c).gl.cols;
    out.push(`      <camera name="${n}" pos="${m3(c.pos)}" xyaxes="${fl([...gl[0], ...gl[1]])}" fovy="${f(c.vfov, 4)}" resolution="${c.spec.width} ${c.spec.height}"/>`);
    // the camera body, visual only
    const b = m.parts.find(p => p.id === `cam_${c.spec.id}`)!;
    const box = b.boxes[0] as typeof b.boxes[0] & { axes?: number[][] };
    out.push(`      <geom name="cam_${n}_body" type="box" pos="${m3(box.c)}" size="${m3(box.s.map(v => v / 2) as [number, number, number])}" quat="${fl(cameraFrames(c).body.quat)}" material="camera_body" contype="0" conaffinity="0" group="1"/>`);
  }
  out.push(`    </body>`, `  </worldbody>`, `</mujoco>`, '');
  return out.join('\n');
}

export function mjcfScene(name = 'table_generator'): string {
  return `<!-- Load this one: the frame plus a floor, lights and a skybox. -->
<mujoco model="${name}_scene">
  <include file="frame.xml"/>
  <statistic center="0 0 0.8" extent="1.6"/>
  <visual>
    <headlight diffuse="0.6 0.6 0.6" ambient="0.3 0.3 0.3" specular="0 0 0"/>
    <rgba haze="0.15 0.25 0.35 1"/>
    <global azimuth="-130" elevation="-25"/>
  </visual>
  <asset>
    <texture type="skybox" builtin="gradient" rgb1="0.3 0.5 0.7" rgb2="0 0 0" width="512" height="3072"/>
    <texture type="2d" name="groundplane" builtin="checker" mark="edge" rgb1="0.2 0.3 0.4" rgb2="0.1 0.2 0.3" markrgb="0.8 0.8 0.8" width="300" height="300"/>
    <material name="groundplane" texture="groundplane" texuniform="true" texrepeat="5 5" reflectance="0.2"/>
  </asset>
  <worldbody>
    <light pos="0 0 3.5" dir="0 0 -1" directional="true"/>
    <geom name="floor" size="0 0 0.05" type="plane" material="groundplane"/>
  </worldbody>
</mujoco>
`;
}
