// URDF: one fixed link for the whole frame (profile meshes for looks, boxes for contact),
// a worktop frame to mount a robot on, and per camera a body link (x forward), an optical
// link (z forward, x right, y down) and a Gazebo camera sensor.
import { Model } from '../model.ts';
import { f, m3, fl, looks, zTo, MEMBER_ROT, memberMid, cameraFrames, safe } from './common.ts';

export function urdf(m: Model, name = 'table_generator'): string {
  const L = looks(m), out: string[] = [];
  out.push(`<?xml version="1.0"?>`, `<!-- Generated by Table Generator. Units: metres, kg. Origin on the floor under the table centre, z up, x across the width, y toward the back. -->`, `<robot name="${name}">`);
  for (const l of Object.values(L)) out.push(`  <material name="${l.name}"><color rgba="${fl(l.rgba, 4)}"/></material>`);
  const I = m.inertia;
  out.push(`  <link name="base_link">`,
    `    <inertial><origin xyz="${m3(m.com)}" rpy="0 0 0"/><mass value="${f(m.mass, 3)}"/><inertia ixx="${f(I[0])}" iyy="${f(I[1])}" izz="${f(I[2])}" ixy="${f(I[3])}" ixz="${f(I[4])}" iyz="${f(I[5])}"/></inertial>`);
  for (const pt of m.parts) {
    if (pt.kind === 'camera') continue;
    const mat = L[pt.role].name;
    if (pt.member) {
      const r = MEMBER_ROT[pt.member.axis];
      out.push(`    <visual name="${pt.id}"><origin xyz="${m3(memberMid(pt))}" rpy="${fl(r.rpy)}"/><geometry><mesh filename="meshes/profile_${pt.member.prof}.stl" scale="1 1 ${f(pt.member.length / 1000)}"/></geometry><material name="${mat}"/></visual>`);
    } else {
      pt.boxes.forEach((b, i) => out.push(`    <visual name="${pt.id}_${i}"><origin xyz="${m3(b.c)}" rpy="0 0 0"/><geometry><box size="${m3(b.s)}"/></geometry><material name="${mat}"/></visual>`));
      pt.cyls.forEach((c, i) => {
        const d: [number, number, number] = [c.b[0] - c.a[0], c.b[1] - c.a[1], c.b[2] - c.a[2]], len = Math.hypot(...d);
        const mid: [number, number, number] = [(c.a[0] + c.b[0]) / 2, (c.a[1] + c.b[1]) / 2, (c.a[2] + c.b[2]) / 2];
        out.push(`    <visual name="${pt.id}_c${i}"><origin xyz="${m3(mid)}" rpy="${fl(zTo(d).rpy)}"/><geometry><cylinder radius="${f(c.r / 1000)}" length="${f(len / 1000)}"/></geometry><material name="${mat}"/></visual>`);
      });
    }
    if (pt.collide) {
      pt.boxes.forEach((b, i) => out.push(`    <collision name="${pt.id}_col${i}"><origin xyz="${m3(b.c)}" rpy="0 0 0"/><geometry><box size="${m3(b.s)}"/></geometry></collision>`));
      pt.cyls.forEach((c, i) => {
        const d: [number, number, number] = [c.b[0] - c.a[0], c.b[1] - c.a[1], c.b[2] - c.a[2]], len = Math.hypot(...d);
        const mid: [number, number, number] = [(c.a[0] + c.b[0]) / 2, (c.a[1] + c.b[1]) / 2, (c.a[2] + c.b[2]) / 2];
        out.push(`    <collision name="${pt.id}_colc${i}"><origin xyz="${m3(mid)}" rpy="${fl(zTo(d).rpy)}"/><geometry><cylinder radius="${f(c.r / 1000)}" length="${f(len / 1000)}"/></geometry></collision>`);
      });
    }
  }
  out.push(`  </link>`);
  out.push(`  <!-- mount a robot here: centre of the worktop surface -->`, `  <link name="worktop_frame"/>`,
    `  <joint name="worktop_joint" type="fixed"><parent link="base_link"/><child link="worktop_frame"/><origin xyz="${m3([0, 0, m.worktopZ])}" rpy="0 0 0"/></joint>`);
  for (const c of m.cameras) {
    const n = safe(c.spec.name), fr = cameraFrames(c);
    out.push(`  <link name="${n}_camera_link"/>`,
      `  <joint name="${n}_camera_joint" type="fixed"><parent link="base_link"/><child link="${n}_camera_link"/><origin xyz="${m3(c.pos)}" rpy="${fl(fr.body.rpy)}"/></joint>`,
      `  <link name="${n}_camera_optical_frame"/>`,
      `  <joint name="${n}_camera_optical_joint" type="fixed"><parent link="${n}_camera_link"/><child link="${n}_camera_optical_frame"/><origin xyz="0 0 0" rpy="${fl([-Math.PI / 2, 0, -Math.PI / 2])}"/></joint>`,
      `  <gazebo reference="${n}_camera_link">`,
      `    <sensor name="${n}_camera" type="camera">`,
      `      <always_on>1</always_on><update_rate>${c.spec.rate}</update_rate><visualize>true</visualize><topic>${n}/image</topic>`,
      `      <camera><horizontal_fov>${f((c.hfov * Math.PI) / 180)}</horizontal_fov><image><width>${c.spec.width}</width><height>${c.spec.height}</height><format>R8G8B8</format></image><clip><near>${f(c.spec.near / 1000)}</near><far>${f(c.spec.far / 1000)}</far></clip><optical_frame_id>${n}_camera_optical_frame</optical_frame_id></camera>`,
      `    </sensor>`,
      `  </gazebo>`);
  }
  out.push(`</robot>`, '');
  return out.join('\n');
}
