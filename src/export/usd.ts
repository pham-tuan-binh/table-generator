// OpenUSD (.usda text): z-up, metres. Visual meshes with UsdPreviewSurface materials,
// invisible Cube/Cylinder colliders with PhysicsCollisionAPI (a static collider, as Isaac
// Sim expects), and a UsdGeom.Camera per camera (looks down -z, +y up).
import * as THREE from 'three';
import { Model, V3 } from '../model.ts';
import { partGeometries, mergeTriangles } from '../geometry.ts';
import { f, looks, zTo, cameraFrames, safe } from './common.ts';

const mat4 = (cols: [V3, V3, V3], t: V3, scale: V3 = [1, 1, 1]) =>
  // USD matrices are row-major with row vectors: rows are the local axes, then the translation
  `( (${cols[0].map(v => f(v * scale[0])).join(', ')}, 0), (${cols[1].map(v => f(v * scale[1])).join(', ')}, 0), (${cols[2].map(v => f(v * scale[2])).join(', ')}, 0), (${t.map(v => f(v / 1000)).join(', ')}, 1) )`;
const I3: [V3, V3, V3] = [[1, 0, 0], [0, 1, 0], [0, 0, 1]];

export function usda(m: Model, name = 'TableGenerator'): string {
  const L = looks(m), o: string[] = [];
  o.push(`#usda 1.0`, `(`, `    defaultPrim = "${name}"`, `    upAxis = "Z"`, `    metersPerUnit = 1`, `    kilogramsPerUnit = 1`, `    doc = "Generated by Table Generator. Origin on the floor under the table centre."`, `)`, '',
    `def Xform "${name}" (`, `    kind = "component"`, `)`, `{`);
  o.push(`    def Scope "Looks"`, `    {`);
  for (const l of Object.values(L)) o.push(
    `        def Material "${l.name}"`, `        {`,
    `            token outputs:surface.connect = </${name}/Looks/${l.name}/Surface.outputs:surface>`,
    `            def Shader "Surface"`, `            {`,
    `                uniform token info:id = "UsdPreviewSurface"`,
    `                color3f inputs:diffuseColor = (${l.rgba.slice(0, 3).map(v => f(v, 4)).join(', ')})`,
    `                float inputs:metallic = ${f(l.metallic, 2)}`,
    `                float inputs:roughness = ${f(l.roughness, 2)}`,
    `                float inputs:opacity = ${f(l.rgba[3], 3)}`,
    `                token outputs:surface`, `            }`, `        }`);
  o.push(`    }`, '');

  // visuals: one mesh per part
  o.push(`    def Xform "Visuals"`, `    {`);
  for (const pt of m.parts) {
    const tri = mergeTriangles(partGeometries(pt, m)), n = tri.length / 3;
    const pts: string[] = [];
    for (let i = 0; i < n; i++) pts.push(`(${f(tri[i * 3] / 1000, 5)}, ${f(tri[i * 3 + 1] / 1000, 5)}, ${f(tri[i * 3 + 2] / 1000, 5)})`);
    o.push(`        def Mesh "${safe(pt.id)}" (`, `            prepend apiSchemas = ["MaterialBindingAPI"]`, `        )`, `        {`,
      `            int[] faceVertexCounts = [${new Array(n / 3).fill(3).join(', ')}]`,
      `            int[] faceVertexIndices = [${Array.from({ length: n }, (_, i) => i).join(', ')}]`,
      `            point3f[] points = [${pts.join(', ')}]`,
      `            uniform token subdivisionScheme = "none"`,
      `            uniform bool doubleSided = 1`,
      `            rel material:binding = </${name}/Looks/${L[pt.role].name}>`,
      `            custom string pf:name = "${pt.name.replace(/"/g, "'")}"`,
      `            custom string pf:spec = "${pt.spec.replace(/"/g, "'")}"`,
      `        }`);
  }
  o.push(`    }`, '');

  // colliders: invisible primitives, static
  o.push(`    def Xform "Colliders"`, `    {`, `        token visibility = "invisible"`);
  for (const pt of m.parts) {
    if (!pt.collide) continue;
    pt.boxes.forEach((b, i) => o.push(
      `        def Cube "${safe(pt.id)}_${i}" (`, `            prepend apiSchemas = ["PhysicsCollisionAPI"]`, `        )`, `        {`,
      `            double size = 1`, `            uniform token purpose = "guide"`,
      `            matrix4d xformOp:transform = ${mat4(I3, b.c, b.s.map(v => v / 1000) as V3)}`,
      `            uniform token[] xformOpOrder = ["xformOp:transform"]`, `        }`));
    pt.cyls.forEach((c, i) => {
      const d: V3 = [c.b[0] - c.a[0], c.b[1] - c.a[1], c.b[2] - c.a[2]], mid: V3 = [(c.a[0] + c.b[0]) / 2, (c.a[1] + c.b[1]) / 2, (c.a[2] + c.b[2]) / 2];
      o.push(`        def Cylinder "${safe(pt.id)}_c${i}" (`, `            prepend apiSchemas = ["PhysicsCollisionAPI"]`, `        )`, `        {`,
        `            uniform token axis = "Z"`, `            double height = ${f(Math.hypot(...d) / 1000)}`, `            double radius = ${f(c.r / 1000)}`, `            uniform token purpose = "guide"`,
        `            matrix4d xformOp:transform = ${mat4(zTo(d).cols, mid)}`,
        `            uniform token[] xformOpOrder = ["xformOp:transform"]`, `        }`);
    });
  }
  o.push(`    }`, '');

  // worktop frame and cameras
  o.push(`    def Xform "worktop_frame"`, `    {`, `        double3 xformOp:translate = (0, 0, ${f(m.worktopZ / 1000)})`, `        uniform token[] xformOpOrder = ["xformOp:translate"]`, `    }`);
  o.push(`    def Xform "Cameras"`, `    {`);
  for (const c of m.cameras) {
    const gl = cameraFrames(c).gl.cols, hAp = 20.955, focal = hAp / (2 * Math.tan((c.hfov * Math.PI) / 360));
    o.push(`        def Camera "${safe(c.spec.name)}"`, `        {`,
      `            matrix4d xformOp:transform = ${mat4(gl, c.pos)}`, `            uniform token[] xformOpOrder = ["xformOp:transform"]`,
      `            float focalLength = ${f(focal, 4)}`, `            float horizontalAperture = ${f(hAp, 4)}`, `            float verticalAperture = ${f((hAp * c.spec.height) / c.spec.width, 4)}`,
      `            float2 clippingRange = (${f(c.spec.near / 1000)}, ${f(c.spec.far / 1000)})`, `            token projection = "perspective"`,
      `            custom int2 pf:resolution = (${c.spec.width}, ${c.spec.height})`, `        }`);
  }
  o.push(`    }`, `}`, '');
  return o.join('\n');
}

// binary STL from triangles in mm, written in metres
export function stl(tri: Float32Array, scale = 0.001): ArrayBuffer {
  const n = tri.length / 9, buf = new ArrayBuffer(84 + n * 50), dv = new DataView(buf);
  const head = 'Table Generator';
  for (let i = 0; i < head.length; i++) dv.setUint8(i, head.charCodeAt(i));
  dv.setUint32(80, n, true);
  const a = new THREE.Vector3(), b = new THREE.Vector3(), c = new THREE.Vector3();
  for (let t = 0; t < n; t++) {
    a.fromArray(tri, t * 9); b.fromArray(tri, t * 9 + 3); c.fromArray(tri, t * 9 + 6);
    const nn = b.clone().sub(a).cross(c.clone().sub(a)).normalize();
    let off = 84 + t * 50;
    for (const v of [nn.x, nn.y, nn.z]) { dv.setFloat32(off, v || 0, true); off += 4; }
    for (const p of [a, b, c]) for (const v of [p.x, p.y, p.z]) { dv.setFloat32(off, v * scale, true); off += 4; }
  }
  return buf;
}
